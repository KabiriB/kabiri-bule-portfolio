import { aggregateByPeriod, fmt, simulateServices, summarizeServices } from "../data/syntheticService";

// The homepage preview is not drawn by hand: it uses the very same fictional
// service accounting engine as the interactive dashboard.
const baseline = simulateServices();
const periods = aggregateByPeriod(baseline, 12);
const summary = summarizeServices(baseline, 12);
const highest = Math.max(...periods.flatMap(row => [row.incoming, row.resolved])) * 1.1;
const chartLine = key => periods.map((row, index) => {
  const x = 16 + index * (598 / (periods.length - 1));
  const y = 171 - row[key] / highest * 142;
  return (index ? "L" : "M") + x.toFixed(1) + " " + y.toFixed(1);
}).join(" ");

export default function DashboardPreview() {
  return (
    <div className="kb-dashboard-art">
      <div className="kb-dashboard-art-top"><span>FICTIONAL SERVICE SYSTEM / REFERENCE RUN</span><span>12 PERIODS</span></div>
      <div className="kb-dashboard-art-stats">
        <div><small>Arrivals</small><b>{fmt(summary.incoming)}</b></div>
        <div><small>Resolved</small><b>{fmt(summary.resolved)}</b></div>
        <div><small>Closing stock</small><b>{fmt(summary.backlog)}</b></div>
      </div>
      <svg viewBox="0 0 630 197" role="img" aria-label="Actual reference-run chart from the synthetic service model: arrivals versus resolved requests in twelve fictional periods">
        {[45, 92, 139, 171].map(y => <line key={y} x1="16" y1={y} x2="614" y2={y} stroke="#8faeb1" strokeOpacity=".25" strokeDasharray="4 8" />)}
        <path d={chartLine("incoming")} stroke="#efbb8d" strokeWidth="3" strokeLinecap="round" strokeLinejoin="round" fill="none" />
        <path d={chartLine("resolved")} stroke="#9fcfca" strokeWidth="3" strokeLinecap="round" strokeLinejoin="round" fill="none" />
        {["P01", "P04", "P08", "P12"].map((label) => {
          const at = periods.findIndex(p => p.period === label);
          const x = 16 + at * 598 / (periods.length - 1);
          return <text key={label} x={x} y="193" fontSize="12" fill="#adcac7" textAnchor="middle">{label}</text>;
        })}
      </svg>
      <div className="kb-dashboard-art-foot">
        <span><i style={{background:"#efbb8d"}} /> Arrivals</span>
        <span><i style={{background:"#9fcfca"}} /> Resolved</span>
        <span>Generated by the actual demonstrator · synthetic data only</span>
      </div>
    </div>
  );
}
